import { describe, expect, it } from 'vitest';
import { buildDb } from './data';
import { searchTests } from './filter';
import { featureCondition, featureLabel, featuresAt, startsFeature } from './features';
import { entry, index, outline } from './fixture';

const par = { id: 'par', tier: 'experimental' as const, flag: '--enable par', summary: 'Pushed Authorization Requests', enabled: false, endpoints: ['par'], packages: [] };
const refresh = { id: 'refresh-token', tier: 'stable' as const, flag: '--disable refresh-token', summary: 'Refresh token', enabled: true, endpoints: [], packages: [] };

describe('feature labels and search', () => {
  it('should distinguish features generated by default from those enabled by a flag', () => {
    expect(featureLabel(par, 'par')).toBe('--enable par');
    expect(featureCondition(par, 'par')).toBe('機能の生成条件: --enable par');
    expect(featureLabel(refresh, 'refresh-token')).toBe('refresh-token · 既定');
    expect(featureCondition(refresh, 'refresh-token')).toContain('--disable refresh-token');
    expect(featureLabel(undefined, 'unknown')).toBe('unknown');
  });

  it('should find directly attributed tests by feature flag without including unrelated tests', () => {
    const db = buildDb(index([
      entry('pushed', { features: ['par'] }),
      entry('common'),
      entry('unrelated', { title: 'should parse a partial request', features: ['ciba'] }),
    ]), { ...outline([]), features: [par, { ...par, id: 'ciba', flag: '--enable ciba' }] });
    expect(searchTests(db, '--enable par').map((test) => test.id)).toEqual(['pushed']);
    expect(searchTests(db, 'par').map((test) => test.id)).toEqual(['pushed']);
    expect(buildDb(index([entry('old')])).features).toEqual([]);
  });
});

describe('feature line ranges', () => {
  const range = { feature: 'par', lines: [10, 20] as [number, number] };

  it('should mark only the owned lines and label a panel that starts inside the range', () => {
    expect(featuresAt([range], 9)).toEqual([]);
    expect(featuresAt([range], 10)).toEqual([range]);
    expect(featuresAt([range], 20)).toEqual([range]);
    expect(featuresAt([range], 21)).toEqual([]);
    expect(startsFeature(range, 15, 15)).toBe(true);
    expect(startsFeature(range, 16, 15)).toBe(false);
    expect(featuresAt(undefined, 10)).toEqual([]);
  });
});
